const plainId = (controlId: string) => { const i = controlId.indexOf(":"); return i >= 0 ? controlId.slice(i + 1) : controlId; };

/** Bereich einer einzelnen Kontrolle. */
export function isoThemeOf(controlId: string): IsoTheme {
  return INDEX.get(plainId(controlId)) ?? INDEX.get(controlId) ?? "ORG";
}

/** Bereich einer Aufgabe mit mehreren Kontrollen: häufigster Bereich, bei Gleichstand die Reihenfolge oben. */
export function isoThemeOfMany(controlIds: readonly string[]): IsoTheme {
  if (controlIds.length === 0) return "ORG";
  const n = new Map<IsoTheme, number>();
  for (const id of controlIds) { const t = isoThemeOf(id); n.set(t, (n.get(t) ?? 0) + 1); }
  let best: IsoTheme = "ORG", max = -1;
  for (const { code } of ISO_THEMES) { const v = n.get(code) ?? 0; if (v > max) { max = v; best = code; } }
  return best;
}

/** ISO-Referenz einer Kontrolle („A.8.15", „6.1.2") — undefined bei fachlich zugeordneten Kontrollen ohne ISO-Bezug. */
export function isoRefOf(controlId: string): string | undefined {
  return REF_INDEX.get(plainId(controlId)) ?? REF_INDEX.get(controlId);
}

/** Häufigste ISO-Referenz einer Aufgabe innerhalb ihres Bereichs. */
export function isoRefOfMany(controlIds: readonly string[], theme: IsoTheme): string | undefined {
  const n = new Map<string, number>();
  for (const id of controlIds) {
    if (isoThemeOf(id) !== theme) continue;
    const r = isoRefOf(id);
    if (r) n.set(r, (n.get(r) ?? 0) + 1);
  }
  let best: string | undefined, max = 0;
  for (const [r, v] of n) if (v > max || (v === max && best !== undefined && r < best)) { best = r; max = v; }
  return best;
}
